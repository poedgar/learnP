/*
 * Copies the JavaScript sandbox runtime from the web app (app/resources/js/lib/js) into
 * src/js-runtime. Run it after changing those files: `npm run sync-js-runtime`.
 * src/js-runtime/__tests__/sync.test.ts fails while the copies are out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

const from = (name) => fileURLToPath(new URL(`../../app/resources/js/lib/js/${name}`, import.meta.url));
const to = (name) => fileURLToPath(new URL(`../src/js-runtime/${name}`, import.meta.url));

export const COPIED = ['prepare.js', 'loop-guard.js', 'engine.js', 'ts-version.js'];

export function sourcesModule() {
  return [
    '// Generated by scripts/sync-js-runtime.mjs from app/resources/js/lib/js. Do not edit.',
    '// Source text injected into sandbox frames and the TypeScript worker (see engine.js).',
    `export const frameRuntimeSource: string = ${JSON.stringify(readFileSync(from('frame-runtime.js'), 'utf8'))};`,
    `export const loopGuardSource: string = ${JSON.stringify(readFileSync(from('loop-guard.js'), 'utf8'))};`,
    `export const tsServiceSource: string = ${JSON.stringify(readFileSync(from('ts-service.js'), 'utf8'))};`,
    "// acorn's UMD build (dist/acorn.js), which defines a global acorn in the frame.",
    `export const acornSource: string = ${JSON.stringify(readFileSync(require.resolve('acorn'), 'utf8'))};`,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const name of COPIED) {
    writeFileSync(to(name), readFileSync(from(name)));
  }
  writeFileSync(to('sources.ts'), sourcesModule());
  console.log(`Copied ${COPIED.join(', ')} and wrote sources.ts.`);
}
