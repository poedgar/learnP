-- Dataset for the SQL practice: library course. Three branches of a town library lend books; loans
-- last 21 days and late returns are fined 0.25 a day. Treat 2026-10-21 as "today".
-- Loaded into a fresh in-memory SQLite database before every sandbox run.

CREATE TABLE branches (
    id      INTEGER PRIMARY KEY,
    name    TEXT NOT NULL,
    address TEXT NOT NULL
);

CREATE TABLE authors (
    id         INTEGER PRIMARY KEY,
    name       TEXT    NOT NULL,
    born       INTEGER NOT NULL
);

CREATE TABLE books (
    id             INTEGER PRIMARY KEY,
    title          TEXT    NOT NULL,
    author_id      INTEGER NOT NULL REFERENCES authors (id),
    genre          TEXT    NOT NULL,
    published_year INTEGER NOT NULL
);

CREATE TABLE copies (
    id          INTEGER PRIMARY KEY,
    book_id     INTEGER NOT NULL REFERENCES books (id),
    branch_id   INTEGER NOT NULL REFERENCES branches (id),
    acquired_on TEXT    NOT NULL
);

CREATE TABLE members (
    id        INTEGER PRIMARY KEY,
    name      TEXT    NOT NULL,
    branch_id INTEGER NOT NULL REFERENCES branches (id),
    joined_on TEXT    NOT NULL
);

CREATE TABLE loans (
    id          INTEGER PRIMARY KEY,
    copy_id     INTEGER NOT NULL REFERENCES copies (id),
    member_id   INTEGER NOT NULL REFERENCES members (id),
    borrowed_on TEXT    NOT NULL,
    due_on      TEXT    NOT NULL,
    returned_on TEXT
);

CREATE TABLE reservations (
    id           INTEGER PRIMARY KEY,
    book_id      INTEGER NOT NULL REFERENCES books (id),
    member_id    INTEGER NOT NULL REFERENCES members (id),
    reserved_on  TEXT    NOT NULL,
    fulfilled_on TEXT
);

