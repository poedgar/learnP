-- Dataset for the SQL practice: online shop course. Inkwell sells stationery online. It covers
-- January to June 2026; treat 2026-07-01 as "today". Money is in pence (price_cents, unit_price_cents).
-- Loaded into a fresh in-memory SQLite database before every sandbox run.

CREATE TABLE customers (
    id        INTEGER PRIMARY KEY,
    name      TEXT NOT NULL,
    email     TEXT NOT NULL,
    city      TEXT,
    joined_on TEXT NOT NULL
);

CREATE TABLE products (
    id          INTEGER PRIMARY KEY,
    name        TEXT    NOT NULL,
    category    TEXT    NOT NULL,
    price_cents INTEGER NOT NULL,
    cost_cents  INTEGER NOT NULL,
    active      INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE orders (
    id             INTEGER PRIMARY KEY,
    customer_id    INTEGER NOT NULL REFERENCES customers (id),
    placed_at      TEXT    NOT NULL,
    status         TEXT    NOT NULL,
    coupon_code    TEXT,
    shipping_cents INTEGER NOT NULL
);

CREATE TABLE order_items (
    order_id         INTEGER NOT NULL REFERENCES orders (id),
    product_id       INTEGER NOT NULL REFERENCES products (id),
    quantity         INTEGER NOT NULL,
    unit_price_cents INTEGER NOT NULL,
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE returns (
    id          INTEGER PRIMARY KEY,
    order_id    INTEGER NOT NULL REFERENCES orders (id),
    product_id  INTEGER NOT NULL REFERENCES products (id),
    quantity    INTEGER NOT NULL,
    reason      TEXT    NOT NULL,
    returned_on TEXT    NOT NULL
);

CREATE TABLE stock_movements (
    id         INTEGER PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products (id),
    moved_on   TEXT    NOT NULL,
    change     INTEGER NOT NULL,
    reason     TEXT    NOT NULL
);

