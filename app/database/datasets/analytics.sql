-- Dataset for the SQL practice: product analytics course. Pagewise is a reading app with a free plan
-- and a paid Pro plan (7.99 a month). It covers January to June 2026; treat 2026-07-01 as "today".
-- Loaded into a fresh in-memory SQLite database before every sandbox run.

CREATE TABLE users (
    id           INTEGER PRIMARY KEY,
    name         TEXT NOT NULL,
    country      TEXT NOT NULL,
    signed_up_on TEXT NOT NULL,
    referrer     TEXT,
    plan         TEXT NOT NULL
);

CREATE TABLE events (
    id          INTEGER PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users (id),
    event       TEXT    NOT NULL,
    happened_at TEXT    NOT NULL
);

CREATE TABLE sessions (
    id               INTEGER PRIMARY KEY,
    user_id          INTEGER NOT NULL REFERENCES users (id),
    started_at       TEXT    NOT NULL,
    duration_seconds INTEGER NOT NULL,
    device           TEXT    NOT NULL
);

CREATE TABLE payments (
    id           INTEGER PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users (id),
    paid_on      TEXT    NOT NULL,
    amount_cents INTEGER NOT NULL,
    status       TEXT    NOT NULL
);

